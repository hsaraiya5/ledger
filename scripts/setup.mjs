#!/usr/bin/env node
// Setup helper for Ledger. docs/SETUP.md walks through when to run each command.
// Secrets go straight into .env.local and are never printed.
//
//   node scripts/setup.mjs init                  create .env.local and generate the app's own secrets
//   node scripts/setup.mjs set KEY=VALUE ...     save values to .env.local
//   node scripts/setup.mjs supabase-keys <ref>   fetch the project's URL and API keys into .env.local
//   node scripts/setup.mjs owner                 record ALLOWED_EMAIL as the database owner
//   node scripts/setup.mjs check                 test every piece of the setup and say what's left
//   node scripts/setup.mjs vercel-env            copy the app's settings to the linked Vercel project
import { execFileSync, spawnSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const ENV = ".env.local";
const SUPABASE = ["-y", "supabase@3"];

/** What the deployed app needs. Values marked local stay on this machine. */
const VARS = [
  { key: "ALLOWED_EMAIL", note: "the one email that can sign in" },
  { key: "NEXT_PUBLIC_SUPABASE_URL", note: "from: node scripts/setup.mjs supabase-keys <ref>" },
  { key: "NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY", note: "from: node scripts/setup.mjs supabase-keys <ref>" },
  { key: "SUPABASE_SECRET_KEY", note: "from: node scripts/setup.mjs supabase-keys <ref>" },
  { key: "SUPABASE_DB_PASSWORD", note: "generated by init", local: true },
  { key: "PLAID_CLIENT_ID", note: "Plaid dashboard > Developers > Keys" },
  { key: "PLAID_SECRET_SANDBOX", note: "Plaid dashboard > Developers > Keys" },
  { key: "PLAID_SECRET_PRODUCTION", note: "only once Plaid approves Production", optional: true },
  { key: "PLAID_ENV", note: "sandbox or production" },
  { key: "PLAID_REDIRECT_URI", note: "https://<your site>/plaid/oauth, for banks that use OAuth in production", optional: true },
  { key: "PLAID_TOKEN_KEY", note: "generated by init" },
  { key: "CRON_SECRET", note: "generated by init" },
  { key: "NEXT_PUBLIC_SITE_URL", note: "your Vercel URL, e.g. https://ledger-yourname.vercel.app", optional: true },
];

// ---- .env.local ----

function readEnv() {
  if (!existsSync(ENV)) return new Map();
  const out = new Map();
  for (const line of readFileSync(ENV, "utf8").split("\n")) {
    const m = line.match(/^([A-Z0-9_]+)=(.*)$/);
    if (m) out.set(m[1], m[2].replace(/^"(.*)"$/, "$1"));
  }
  return out;
}

function writeEnv(updates) {
  const lines = existsSync(ENV) ? readFileSync(ENV, "utf8").split("\n") : [];
  for (const [k, v] of Object.entries(updates)) {
    const i = lines.findIndex((l) => l.startsWith(`${k}=`));
    if (i >= 0) lines[i] = `${k}=${v}`;
    else lines.splice(lines.length && lines[lines.length - 1] === "" ? lines.length - 1 : lines.length, 0, `${k}=${v}`);
  }
  writeFileSync(ENV, lines.join("\n").replace(/\n*$/, "\n"), { mode: 0o600 });
}

const ok = (msg) => console.log(`  ✓ ${msg}`);
const bad = (msg) => console.log(`  ✗ ${msg}`);
const fail = (msg) => { console.error(msg); process.exit(1); };

// ---- Commands ----

function init() {
  if (!existsSync(ENV)) writeFileSync(ENV, readFileSync(".env.example", "utf8"), { mode: 0o600 });
  const env = readEnv();
  const generated = {};
  if (!env.get("PLAID_TOKEN_KEY")) generated.PLAID_TOKEN_KEY = randomBytes(32).toString("base64");
  if (!env.get("CRON_SECRET")) generated.CRON_SECRET = randomBytes(24).toString("hex");
  // Letters and digits only, so it's safe in a connection string.
  if (!env.get("SUPABASE_DB_PASSWORD")) generated.SUPABASE_DB_PASSWORD = randomBytes(24).toString("base64url").replace(/[-_]/g, "x");
  if (!env.get("PLAID_ENV")) generated.PLAID_ENV = "sandbox";
  writeEnv(generated);
  console.log(`${ENV} is ready. Generated: ${Object.keys(generated).join(", ") || "nothing new"}.`);
}

function set(pairs) {
  const updates = {};
  for (const p of pairs) {
    const i = p.indexOf("=");
    if (i < 1) fail(`Expected KEY=VALUE, got "${p}".`);
    const k = p.slice(0, i), v = p.slice(i + 1).trim();
    if (!VARS.some((x) => x.key === k)) fail(`${k} isn't a setting Ledger uses. Known: ${VARS.map((x) => x.key).join(", ")}`);
    updates[k] = k === "ALLOWED_EMAIL" ? v.toLowerCase() : v;
  }
  writeEnv(updates);
  console.log(`Saved ${Object.keys(updates).join(", ")}.`);
}

function supabaseKeys(ref) {
  if (!ref) fail("Usage: node scripts/setup.mjs supabase-keys <project-ref>");
  let keys;
  try {
    keys = JSON.parse(execFileSync("npx", [...SUPABASE, "projects", "api-keys", `--remote=${ref}`, "--reveal", "-o", "json"], { encoding: "utf8", stdio: ["ignore", "pipe", "inherit"] }));
  } catch {
    fail("Couldn't read the project's keys. Is the Supabase CLI logged in (npx -y supabase@3 login) and the project finished creating?");
  }
  const list = Array.isArray(keys) ? keys : keys.keys ?? Object.values(keys);
  const value = (k) => k.api_key ?? k.key ?? k.value ?? "";
  // Prefer the newer publishable/secret keys; fall back to the legacy anon/service_role ones.
  const pub = list.find((k) => value(k).startsWith("sb_publishable_")) ?? list.find((k) => k.name === "anon");
  const sec = list.find((k) => value(k).startsWith("sb_secret_")) ?? list.find((k) => k.name === "service_role");
  if (!pub || !sec || !value(sec) || value(sec).includes("·")) fail("The CLI didn't return full keys. Copy them from the Supabase dashboard (Project Settings > API Keys) with `set` instead.");
  writeEnv({ NEXT_PUBLIC_SUPABASE_URL: `https://${ref}.supabase.co`, NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY: value(pub), SUPABASE_SECRET_KEY: value(sec) });
  console.log("Saved the Supabase URL, publishable key and secret key.");
}

async function rest(env, path, init = {}) {
  const key = env.get("SUPABASE_SECRET_KEY");
  return fetch(`${env.get("NEXT_PUBLIC_SUPABASE_URL")}/rest/v1/${path}`, {
    ...init,
    headers: { apikey: key, ...(key.startsWith("sb_") ? {} : { Authorization: `Bearer ${key}` }), "Content-Type": "application/json", ...init.headers },
  });
}

async function owner() {
  const env = readEnv();
  for (const k of ["ALLOWED_EMAIL", "NEXT_PUBLIC_SUPABASE_URL", "SUPABASE_SECRET_KEY"]) if (!env.get(k)) fail(`${k} isn't set yet.`);
  const r = await rest(env, "rpc/set_owner", { method: "POST", body: JSON.stringify({ owner_email: env.get("ALLOWED_EMAIL") }) });
  if (!r.ok) fail(`Couldn't set the owner (${r.status}): ${await r.text()}. Has the schema been pushed (npx -y supabase@3 db push)?`);
  console.log(`The database now belongs to ${env.get("ALLOWED_EMAIL")}.`);
}

async function check() {
  const env = readEnv();
  let missing = 0;
  console.log("Settings in .env.local");
  for (const v of VARS) {
    if (env.get(v.key)) ok(v.key);
    else if (v.optional) console.log(`  · ${v.key} (optional: ${v.note})`);
    else { bad(`${v.key}: ${v.note}`); missing++; }
  }
  if (env.get("PLAID_TOKEN_KEY") && Buffer.from(env.get("PLAID_TOKEN_KEY"), "base64").length !== 32) { bad("PLAID_TOKEN_KEY must be 32 bytes, base64. Clear it and run init again."); missing++; }

  console.log("Supabase");
  if (env.get("NEXT_PUBLIC_SUPABASE_URL") && env.get("SUPABASE_SECRET_KEY")) {
    try {
      const r = await rest(env, "categories?select=name");
      if (r.ok) ok(`schema is in place (${(await r.json()).length} categories)`);
      else { bad(`schema not found (${r.status}). Run: npx -y supabase@3 db push --remote=<ref> --password <SUPABASE_DB_PASSWORD> --yes`); missing++; }
      const pub = await fetch(`${env.get("NEXT_PUBLIC_SUPABASE_URL")}/rest/v1/categories?select=name`, { headers: { apikey: env.get("NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY") ?? "" } });
      if (pub.ok && (await pub.json()).length === 0) ok("signed-out visitors see nothing");
      else if (pub.status === 401 || pub.status === 403 || pub.status === 404) ok("signed-out visitors see nothing");
      else { bad("signed-out visitors can read data: the schema's access rules didn't apply"); missing++; }
    } catch (e) { bad(`can't reach Supabase: ${e.message}`); missing++; }
  } else console.log("  · waiting on the Supabase settings above");

  console.log("Plaid");
  const plaidEnv = env.get("PLAID_ENV") === "production" ? "production" : "sandbox";
  const secret = plaidEnv === "production" ? env.get("PLAID_SECRET_PRODUCTION") : env.get("PLAID_SECRET_SANDBOX");
  if (env.get("PLAID_CLIENT_ID") && secret) {
    const r = await fetch(`https://${plaidEnv}.plaid.com/institutions/get`, {
      method: "POST", headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ client_id: env.get("PLAID_CLIENT_ID"), secret, count: 1, offset: 0, country_codes: ["US"] }),
    });
    if (r.ok) ok(`${plaidEnv} keys work`);
    else { bad(`Plaid rejected the ${plaidEnv} keys (${(await r.json()).error_code ?? r.status})`); missing++; }
  } else console.log(`  · waiting on PLAID_CLIENT_ID and the ${plaidEnv} secret`);

  console.log("Vercel");
  if (existsSync(".vercel/project.json")) ok(`linked to ${JSON.parse(readFileSync(".vercel/project.json", "utf8")).projectName ?? "a project"}`);
  else console.log("  · not linked yet (npx vercel link)");

  console.log(missing ? `\n${missing} thing(s) left.` : "\nEverything checks out.");
  process.exitCode = missing ? 1 : 0;
}

function vercelEnv() {
  if (!existsSync(".vercel/project.json")) fail("Link a Vercel project first: npx vercel link");
  const env = readEnv();
  for (const v of VARS) {
    const value = env.get(v.key);
    if (v.local || !value) continue;
    spawnSync("npx", ["vercel", "env", "rm", v.key, "production", "--yes"], { stdio: "ignore" });
    const r = spawnSync("npx", ["vercel", "env", "add", v.key, "production"], { input: value, stdio: ["pipe", "ignore", "pipe"], encoding: "utf8" });
    if (r.status !== 0) fail(`Couldn't add ${v.key}: ${r.stderr.trim()}`);
    console.log(`  ✓ ${v.key}`);
  }
  console.log("Vercel has every setting. Deploy with: npx vercel deploy --prod");
}

const [cmd, ...args] = process.argv.slice(2);
const commands = { init, set: () => set(args), "supabase-keys": () => supabaseKeys(args[0]), owner, check, "vercel-env": vercelEnv };
if (!commands[cmd]) fail(readFileSync(new URL(import.meta.url), "utf8").split("\n").slice(1, 10).map((l) => l.replace(/^\/\/ ?/, "")).join("\n"));
await commands[cmd]();
